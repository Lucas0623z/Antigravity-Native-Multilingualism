'use strict';
/**
 * 构建 dist/payload（嵌入 app.asar 的运行时）：
 *   boot.js, main/*.js, shared/matcher.js, preload.bundle.js, locales/*.json
 * preload 在沙盒渲染进程里不能 require 本地文件，因此打包成单文件。
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'dist', 'payload');

function rmrf(p) {
  fs.rmSync(p, { recursive: true, force: true });
}

function copy(rel) {
  const from = path.join(SRC, rel);
  const to = path.join(OUT, rel);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

/** 极简 CommonJS 打包：把相对 require 改写成模块 id */
function bundle(entryRel) {
  const modules = new Map();
  const visit = (rel) => {
    const id = rel.replace(/\\/g, '/');
    if (modules.has(id)) return;
    const src = fs.readFileSync(path.join(SRC, rel), 'utf8');
    modules.set(id, null);
    const rewritten = src.replace(/require\((['"])(\.{1,2}\/[^'"]+)\1\)/g, (_m, _q, spec) => {
      const dep = path.posix.normalize(path.posix.join(path.posix.dirname(id), spec));
      visit(dep);
      return `__agyReq(${JSON.stringify(dep)})`;
    });
    modules.set(id, rewritten);
  };
  visit(entryRel);
  const parts = [
    '/* agy-i18n preload bundle — generated by tools/build.js, do not edit */',
    '(function () {',
    "'use strict';",
    'const __agyMods = Object.create(null);',
    'const __agyCache = Object.create(null);',
    'function __agyReq(id) {',
    '  if (__agyCache[id]) return __agyCache[id].exports;',
    '  const m = { exports: {} };',
    '  __agyCache[id] = m;',
    '  __agyMods[id](m, m.exports);',
    '  return m.exports;',
    '}',
  ];
  for (const [id, code] of modules) {
    parts.push(`__agyMods[${JSON.stringify(id)}] = function (module, exports) {\n${code}\n};`);
  }
  parts.push(`__agyReq(${JSON.stringify(entryRel)});`, '})();', '');
  return parts.join('\n');
}

function build() {
  rmrf(OUT);
  fs.mkdirSync(OUT, { recursive: true });
  copy('boot.js');
  for (const f of fs.readdirSync(path.join(SRC, 'main'))) copy(path.join('main', f));
  copy(path.join('shared', 'matcher.js'));
  fs.writeFileSync(path.join(OUT, 'preload.bundle.js'), bundle('renderer/preload.js'));

  const locDir = path.join(ROOT, 'locales');
  fs.mkdirSync(path.join(OUT, 'locales'), { recursive: true });
  for (const f of fs.readdirSync(locDir).filter((n) => n.endsWith('.json'))) {
    // 压缩 JSON
    const data = JSON.parse(fs.readFileSync(path.join(locDir, f), 'utf8'));
    fs.writeFileSync(path.join(OUT, 'locales', f), JSON.stringify(data));
  }
  return OUT;
}

if (require.main === module) {
  const out = build();
  const files = [];
  const walk = (d, p = '') => {
    for (const n of fs.readdirSync(d)) {
      const full = path.join(d, n);
      if (fs.statSync(full).isDirectory()) walk(full, `${p}${n}/`);
      else files.push(`${p}${n} (${fs.statSync(full).size} B)`);
    }
  };
  walk(out);
  process.stdout.write(`built ${out}\n  ${files.join('\n  ')}\n`);
}

module.exports = { build, bundle };
